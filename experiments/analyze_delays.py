"""Step 10 analysis: H1 and H2 from results/delays.csv (reads the CSV only).

Outputs:
  results/plots/degradation_vs_p_<model>.png   median degradation vs p, IQR, per map
  results/plots/density_vs_degradation.png      Type-2 density vs degradation at p = 0.1
  results/delay_summary.md                      tables generated by code

Unit of analysis: one solution = (map, scen, k, algorithm); its degradation at (model, p) is the
mean over the R trials. H1 pairs the CBS and PP solutions of the same instance.
"""
from __future__ import annotations

import argparse
import math
import os
import sys
from collections import defaultdict

import numpy as np
from scipy import stats

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from experiments import plotstyle as ps  # noqa: E402
from experiments.util import ROOT, read_csv, read_header, rel  # noqa: E402

MAP_ORDER = ["empty-32-32", "random-32-32-10", "room-32-32-4"]


def aggregate(rows):
    """{(model, p): {(map, scen, k, alg): dict}} with mean degradation over trials."""
    acc = defaultdict(lambda: defaultdict(list))
    meta = {}
    for r in rows:
        key = (r["map"], int(r["scen"]), int(r["k"]), r["algorithm"])
        acc[(r["model"], float(r["p"]))][key].append(float(r["degradation"]))
        meta[key] = {"density": float(r["type2_density"]), "k": int(r["k"]), "edges": int(r["type2_edges"]),
                     "num_actions": int(r["num_actions"]),
                     "plan_hash": r.get("plan_hash", ""), "planned_soc": int(r["planned_soc"]),
                     "exec_soc_p0": int(r["exec_soc_p0"])}
    out = {}
    for mp, d in acc.items():
        out[mp] = {key: dict(meta[key], deg=float(np.mean(v)), n=len(v)) for key, v in d.items()}
    return out, meta


def reference_degradation(rec, model, p, burst_len=5):
    """Degradation if no robot ever waited for another robot.

    A ready robot needs p/(1-p) extra steps per move on average under per-step delays
    (D*p/(1-p) under bursts of length D). Spread over all moves and divided by the p = 0 executed
    SOC, this is what independent robots would lose; anything above it comes from robots
    waiting on each other through Type-2 edges.
    """
    per_move = p / (1 - p) * (burst_len if model == "burst" else 1)
    return rec["num_actions"] * per_move / rec["exec_soc_p0"] if rec["exec_soc_p0"] else 0.0


def maps_in(meta):
    present = {k[0] for k in meta}
    return [m for m in MAP_ORDER if m in present] + sorted(present - set(MAP_ORDER))


def pairs_of(sol):
    """[(instance, cbs_record, pp_record)] for instances with both solutions."""
    inst = defaultdict(dict)
    for (m, s, k, alg), rec in sol.items():
        inst[(m, s, k)][alg] = rec
    return [(key, v["cbs"], v["pp"]) for key, v in sorted(inst.items()) if "cbs" in v and "pp" in v]


def wilcoxon_row(diffs):
    diffs = np.asarray(diffs, dtype=float)
    n = len(diffs)
    if n == 0:
        return None
    nz = diffs[np.abs(diffs) > 1e-12]
    if len(nz) < 5:
        pval, w = float("nan"), float("nan")
    else:
        res = stats.wilcoxon(nz, alternative="two-sided")
        w, pval = float(res.statistic), float(res.pvalue)
    return {"n": n, "median": float(np.median(diffs)), "mean": float(np.mean(diffs)),
            "cbs_worse": float(np.mean(diffs > 0)), "W": w, "p": pval}


def holm(pvals):
    """Holm-Bonferroni adjusted p-values (NaNs are left as NaN)."""
    idx = [i for i, v in enumerate(pvals) if not math.isnan(v)]
    order = sorted(idx, key=lambda i: pvals[i])
    adj = [float("nan")] * len(pvals)
    running = 0.0
    for rank, i in enumerate(order):
        running = max(running, min(1.0, (len(order) - rank) * pvals[i]))
        adj[i] = running
    return adj


def spearman(x, y):
    if len(x) < 5 or np.std(x) == 0 or np.std(y) == 0:
        return float("nan"), float("nan")
    r = stats.spearmanr(x, y)
    return float(r.statistic), float(r.pvalue)


def partial_spearman(x, y, z):
    """Spearman correlation of x and y controlling for z (rank partial correlation)."""
    n = len(x)
    if n < 6:
        return float("nan"), float("nan")
    rxy, _ = spearman(x, y)
    rxz, _ = spearman(x, z)
    ryz, _ = spearman(y, z)
    if any(math.isnan(v) for v in (rxy, rxz, ryz)) or abs(rxz) >= 1 or abs(ryz) >= 1:
        return float("nan"), float("nan")
    r = (rxy - rxz * ryz) / math.sqrt((1 - rxz**2) * (1 - ryz**2))
    t = r * math.sqrt((n - 3) / max(1e-12, 1 - r**2))
    return r, float(2 * stats.t.sf(abs(t), n - 3))


def fmt_p(p):
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return "n/a"
    return f"{p:.2e}" if p < 1e-3 else f"{p:.3f}"


def plot_degradation(agg, model, maps, out):
    import matplotlib.pyplot as plt

    ps_levels = sorted({p for (mo, p) in agg if mo == model})
    fig, axes = plt.subplots(1, len(maps), figsize=(4.2 * len(maps), 3.4), sharey=True, squeeze=False)
    for ax, m in zip(axes[0], maps):
        ends = {}
        for alg in ps.ALGS:
            q = []
            for p in ps_levels:
                v = [rec["deg"] for (mm, s, k, a), rec in agg[(model, p)].items() if mm == m and a == alg]
                q.append(np.percentile(v, [25, 50, 75]) if v else [np.nan] * 3)
            q = np.array(q)
            ax.fill_between(ps_levels, q[:, 0], q[:, 2], color=ps.COLORS[alg], alpha=0.18, linewidth=0)
            ax.plot(ps_levels, q[:, 1], color=ps.COLORS[alg], marker=ps.MARKERS[alg], label=ps.LABELS[alg])
            ends[alg] = (ps_levels[-1], q[-1, 1])
        ps.end_labels(ax, ends)
        ax.set_title(m)
        ax.set_xlabel("delay probability p")
        ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda v, _: f"{v:.0%}"))
    axes[0][0].set_ylabel("degradation vs p = 0")
    axes[0][0].legend(loc="upper left")
    name = "per-step" if model == "per_step" else "burst (D = 5)"
    fig.suptitle(f"Executed SOC increase under ADG execution, {name} delays (median, IQR)",
                 x=0.01, ha="left", fontweight="bold")
    fig.tight_layout()
    fig.savefig(out, dpi=150)
    plt.close(fig)


def plot_density(agg, model, p, out):
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(figsize=(5.6, 4.0))
    for alg in ps.ALGS:
        xs = [rec["density"] for key, rec in agg[(model, p)].items() if key[3] == alg]
        ys = [rec["deg"] for key, rec in agg[(model, p)].items() if key[3] == alg]
        ax.scatter(xs, ys, s=22, color=ps.COLORS[alg], marker=ps.MARKERS[alg], alpha=0.55,
                   edgecolors=ps.SURFACE, linewidths=0.6, label=ps.LABELS[alg])
    ax.set_xlabel("Type-2 edges per action (density)")
    ax.set_ylabel(f"mean degradation at p = {p}")
    ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda v, _: f"{v:.0%}"))
    ref = p / (1 - p) if model == "per_step" else 5 * p / (1 - p)
    ax.axhline(ref, color=ps.TEXT2, linewidth=1, linestyle=(0, (4, 3)))
    ax.annotate(f"no-coupling reference p/(1-p) = {ref:.1%}", (ax.get_xlim()[1], ref), xytext=(-4, -10),
                textcoords="offset points", ha="right", va="top", fontsize=8, color=ps.TEXT2,
                bbox=dict(boxstyle="round,pad=0.25", fc=ps.SURFACE, ec="none"))
    ps.solid_legend(ax, loc="lower right", markerscale=1.4)
    ax.set_title(f"Coupling density vs degradation ({model.replace('_', '-')}, p = {p})", loc="left")
    fig.tight_layout()
    fig.savefig(out, dpi=150)
    plt.close(fig)


def build_summary(agg, meta, header, csv_path):
    maps = maps_in(meta)
    models = [m for m in ("per_step", "burst") if any(mo == m for mo, _ in agg)]
    L = ["# Delay-robustness summary (Step 10)", "",
         f"Generated by `experiments/analyze_delays.py` from `{rel(csv_path)}`. Do not edit by hand.", "",
         "## Setup", "",
         f"- Paired instances (solved by both CBS and PP): {header.get('paired_instances', '?')}",
         f"- Trials per (solution, p, model): {header.get('trials', '?')}; p levels: {header.get('p_levels', '?')}",
         f"- Delay models: {header.get('models', '?')} (burst length {header.get('burst_len', '?')})",
         f"- Seeds: {header.get('seed_rule', '?')}; wall time {header.get('total_wall_s', '?')} s; "
         f"benchmark commit {header.get('benchmark_git_commit', '?')}",
         "- Degradation = executed SOC at p / executed SOC at p = 0, minus 1, averaged over trials.",
         "- Every simulated trace passed the execution checker (the runner aborts otherwise).", ""]

    any_key = next(iter(agg))
    sol0 = agg[any_key]
    pr = pairs_of(sol0)
    same = sum(1 for _, c, p in pr if c["plan_hash"] and c["plan_hash"] == p["plan_hash"])
    L += ["## The plans", "",
          f"- CBS and PP returned the *identical* plan on {same} of {len(pr)} paired instances; there the "
          "CBS-PP difference is pure simulation noise. H1 is reported on all pairs and on pairs whose plans differ.", ""]
    L += ["| map | pairs | mean k | mean density CBS | mean density PP | mean p=0 exec SOC / planned SOC, CBS | same, PP "
          "| moves / p=0 exec SOC, CBS | same, PP |",
          "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for m in maps + ["all"]:
        sub = [(key, c, p) for key, c, p in pr if m == "all" or key[0] == m]
        if not sub:
            continue
        L.append(f"| {m} | {len(sub)} | {np.mean([key[2] for key, _, _ in sub]):.1f} | "
                 f"{np.mean([c['density'] for _, c, _ in sub]):.3f} | {np.mean([p['density'] for _, _, p in sub]):.3f} | "
                 f"{np.mean([c['exec_soc_p0'] / c['planned_soc'] for _, c, _ in sub]):.4f} | "
                 f"{np.mean([p['exec_soc_p0'] / p['planned_soc'] for _, _, p in sub]):.4f} | "
                 f"{np.mean([c['num_actions'] / c['exec_soc_p0'] for _, c, _ in sub if c['exec_soc_p0']]):.4f} | "
                 f"{np.mean([p['num_actions'] / p['exec_soc_p0'] for _, _, p in sub if p['exec_soc_p0']]):.4f} |")
    L += ["", "p=0 exec SOC / planned SOC = 1 confirms that, without delays, ADG execution reproduces the plan. "
          "moves / p=0 exec SOC below 1 means the plan contains waits that are needed (a robot waiting for another).", ""]

    for model in models:
        p_levels = sorted(p for mo, p in agg if mo == model and p > 0)
        L += [f"## H1 ({model.replace('_', '-')} delays): do CBS plans degrade more than PP plans?", "",
              "Paired Wilcoxon signed-rank test (two-sided) on per-instance mean degradation. "
              "Difference = CBS minus PP; positive means CBS degrades more.", "",
              "Holm-adjusted p-values correct for the four p levels within each subset.", "",
              "| p | subset | pairs | median diff | mean diff | share CBS worse | W | p-value | Holm p |",
              "|---:|---|---:|---:|---:|---:|---:|---:|---:|"]
        for label in ("all pairs", "plans differ"):
            ws = []
            for p in p_levels:
                prs = pairs_of(agg[(model, p)])
                if label == "plans differ":
                    prs = [x for x in prs if x[1]["plan_hash"] != x[2]["plan_hash"]]
                ws.append((p, wilcoxon_row([c["deg"] - pp_["deg"] for _, c, pp_ in prs])))
            adj = holm([w["p"] for _, w in ws])
            for (p, w), a in zip(ws, adj):
                L.append(f"| {p} | {label} | {w['n']} | {w['median']:+.4f} | {w['mean']:+.4f} | "
                         f"{w['cbs_worse']:.1%} | {w['W']:.0f} | {fmt_p(w['p'])} | {fmt_p(a)} |")
        L.append("")
        L += [f"Per map, plans differ ({model.replace('_', '-')}):", "",
              "| map | p | pairs | median diff | share CBS worse | p-value |", "|---|---:|---:|---:|---:|---:|"]
        for m in maps:
            for p in p_levels:
                sub = [x for x in pairs_of(agg[(model, p)]) if x[0][0] == m and x[1]["plan_hash"] != x[2]["plan_hash"]]
                w = wilcoxon_row([c["deg"] - pp_["deg"] for _, c, pp_ in sub])
                if w:
                    L.append(f"| {m} | {p} | {w['n']} | {w['median']:+.4f} | {w['cbs_worse']:.1%} | {fmt_p(w['p'])} |")
        L.append("")

        L += [f"## H2 ({model.replace('_', '-')} delays): does Type-2 density predict degradation?", "",
              "Spearman rank correlations over solutions. `rho(density, deg | k)` is the rank partial correlation "
              "controlling for the number of agents, to show whether density adds signal beyond crowding.", "",
              "| p | set | n | rho(density, deg) | p-value | rho(k, deg) | p-value | rho(density, k) | rho(density, deg \\| k) | p-value |",
              "|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for p in p_levels:
            sol = agg[(model, p)]
            for label, algs in (("all", ("cbs", "pp")), ("CBS", ("cbs",)), ("PP", ("pp",))):
                recs = [rec for key, rec in sol.items() if key[3] in algs]
                x = np.array([r["density"] for r in recs])
                y = np.array([r["deg"] for r in recs])
                z = np.array([r["k"] for r in recs], dtype=float)
                r1, p1 = spearman(x, y)
                r2, p2 = spearman(z, y)
                r3, _ = spearman(x, z)
                r4, p4 = partial_spearman(x, y, z)
                L.append(f"| {p} | {label} | {len(recs)} | {r1:+.3f} | {fmt_p(p1)} | {r2:+.3f} | {fmt_p(p2)} | "
                         f"{r3:+.3f} | {r4:+.3f} | {fmt_p(p4)} |")
        L.append("")

    for model in models:
        bl = int(header.get("burst_len", 5) or 5)
        L += [f"## How much of the slowdown comes from coupling? ({model.replace('_', '-')})", "",
              "Reference = degradation if no robot ever waited for another "
              f"({'p/(1-p)' if model == 'per_step' else f'{bl}p/(1-p)'} extra steps per move, over p = 0 executed SOC). "
              "Excess = degradation minus reference: the part caused by robots waiting on each other. "
              "Medians over solutions; H1 on the excess uses the same paired Wilcoxon test (plans differ). "
              "*Exploratory, not the pre-registered H1 metric:* the reference is not a strict bound (waits already in "
              "a plan can absorb a robot's own delays), and it is lower for plans with more waiting, so differences "
              "in excess partly reflect how much waiting each plan contains.", "",
              "| p | reference (median) | CBS degradation | PP degradation | CBS excess | PP excess | "
              "excess diff CBS-PP (median) | p-value | rho(density, excess) | rho(density, excess \\| k) |",
              "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for p in sorted(p for mo, p in agg if mo == model and p > 0):
            sol = agg[(model, p)]
            ref = {key: reference_degradation(rec, model, p, bl) for key, rec in sol.items()}
            exc = {key: rec["deg"] - ref[key] for key, rec in sol.items()}

            def med(vals):
                return f"{np.median(vals):.2%}" if len(vals) else "-"
            prs = [x for x in pairs_of(sol) if x[1]["plan_hash"] != x[2]["plan_hash"]]
            w = wilcoxon_row([exc[(*key, "cbs")] - exc[(*key, "pp")] for key, _, _ in prs])
            keys = list(sol)
            x = np.array([sol[kk]["density"] for kk in keys])
            y = np.array([exc[kk] for kk in keys])
            z = np.array([sol[kk]["k"] for kk in keys], dtype=float)
            r1, _ = spearman(x, y)
            r2, p2 = partial_spearman(x, y, z)
            L.append(f"| {p} | {med(list(ref.values()))} | "
                     f"{med([r['deg'] for kk, r in sol.items() if kk[3] == 'cbs'])} | "
                     f"{med([r['deg'] for kk, r in sol.items() if kk[3] == 'pp'])} | "
                     f"{med([v for kk, v in exc.items() if kk[3] == 'cbs'])} | "
                     f"{med([v for kk, v in exc.items() if kk[3] == 'pp'])} | "
                     f"{w['median']:+.4f} | {fmt_p(w['p'])} | {r1:+.3f} | {r2:+.3f} (p {fmt_p(p2)}) |")
        L.append("")

    L += ["## Median degradation by map and p (per-step)", "",
          "| map | p | CBS median | PP median | CBS IQR | PP IQR |", "|---|---:|---:|---:|---|---|"]
    if "per_step" in models:
        for m in maps:
            for p in sorted(p for mo, p in agg if mo == "per_step" and p > 0):
                row = [m, str(p)]
                iq = []
                for alg in ("cbs", "pp"):
                    v = [rec["deg"] for key, rec in agg[("per_step", p)].items() if key[0] == m and key[3] == alg]
                    q = np.percentile(v, [25, 50, 75])
                    row.append(f"{q[1]:.2%}")
                    iq.append(f"{q[0]:.2%} to {q[2]:.2%}")
                L.append("| " + " | ".join(row + iq) + " |")
    L.append("")
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--csv", default=os.path.join(ROOT, "results", "delays.csv"))
    ap.add_argument("--out-dir", default=os.path.join(ROOT, "results"))
    args = ap.parse_args()
    ps.setup()
    rows = read_csv(args.csv)
    header = read_header(args.csv)
    agg, meta = aggregate(rows)
    maps = maps_in(meta)
    os.makedirs(os.path.join(args.out_dir, "plots"), exist_ok=True)
    for model in sorted({mo for mo, _ in agg}):
        plot_degradation(agg, model, maps, os.path.join(args.out_dir, "plots", f"degradation_vs_p_{model}.png"))
    if ("per_step", 0.1) in agg:
        plot_density(agg, "per_step", 0.1, os.path.join(args.out_dir, "plots", "density_vs_degradation.png"))
    md = build_summary(agg, meta, header, args.csv)
    with open(os.path.join(args.out_dir, "delay_summary.md"), "w", encoding="utf-8") as f:
        f.write(md + "\n")
    print(f"wrote {args.out_dir}/delay_summary.md and plots/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
