"""Step 8: analyse results/benchmark.csv (reads the CSV only, never re-runs a solver).

Outputs:
  results/plots/success_rate.png   success rate vs k, one panel per map
  results/plots/runtime.png        runtime vs k (solved runs, log scale), median + IQR
  results/summary.md               tables generated from the CSV
"""
from __future__ import annotations

import argparse
import os
import sys
from collections import defaultdict
from statistics import mean

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from experiments import plotstyle as ps  # noqa: E402
from experiments.util import ROOT, read_csv, read_header  # noqa: E402

MAP_ORDER = ["empty-32-32", "random-32-32-10", "room-32-32-4"]


def load(path):
    rows = read_csv(path)
    for r in rows:
        r["k"], r["scen"], r["success"] = int(r["k"]), int(r["scen"]), int(r["success"])
        r["runtime_s"] = float(r["runtime_s"])
        r["soc"] = int(r["soc"]) if r["soc"] else None
    return rows


def maps_in(rows):
    present = {r["map"] for r in rows}
    return [m for m in MAP_ORDER if m in present] + sorted(present - set(MAP_ORDER))


def success_table(rows):
    """{(map, alg): {k: (solved, runs)}}"""
    t = defaultdict(lambda: defaultdict(lambda: [0, 0]))
    for r in rows:
        cell = t[(r["map"], r["algorithm"])][r["k"]]
        cell[0] += r["success"]
        cell[1] += 1
    return t


def max_k_at(table, m, alg, thresh=0.5):
    ks = [k for k, (s, n) in table[(m, alg)].items() if n and s / n >= thresh]
    return max(ks) if ks else 0


def paired(rows):
    """{(map, scen, k): {alg: row}} restricted to instances solved by both algorithms."""
    by = defaultdict(dict)
    for r in rows:
        if r["success"]:
            by[(r["map"], r["scen"], r["k"])][r["algorithm"]] = r
    return {key: v for key, v in by.items() if "cbs" in v and "pp" in v}


def plot_success(rows, table, out):
    import matplotlib.pyplot as plt

    maps = maps_in(rows)
    fig, axes = plt.subplots(1, len(maps), figsize=(4.2 * len(maps), 3.4), sharey=True, squeeze=False)
    for ax, m in zip(axes[0], maps):
        for alg in ps.ALGS:
            d = table.get((m, alg))
            if not d:
                continue
            ks = sorted(d)
            ys = [d[k][0] / d[k][1] for k in ks]
            ax.plot(ks, ys, color=ps.COLORS[alg], marker=ps.MARKERS[alg], label=ps.LABELS[alg])
            ps.end_label(ax, ks[-1], ys[-1], alg)
        ax.set_title(m)
        ax.set_xlabel("agents (k)")
        ax.set_ylim(-0.03, 1.05)
        ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda v, _: f"{v:.0%}"))
    axes[0][0].set_ylabel("success rate")
    axes[0][-1].legend(loc="upper right")
    fig.suptitle("Instances solved within the time limit", x=0.01, ha="left", fontweight="bold")
    fig.tight_layout()
    fig.savefig(out, dpi=150)
    plt.close(fig)


def plot_runtime(rows, out):
    import matplotlib.pyplot as plt

    maps = maps_in(rows)
    fig, axes = plt.subplots(1, len(maps), figsize=(4.2 * len(maps), 3.4), sharey=True, squeeze=False)
    for ax, m in zip(axes[0], maps):
        for alg in ps.ALGS:
            byk = defaultdict(list)
            for r in rows:
                if r["map"] == m and r["algorithm"] == alg and r["success"]:
                    byk[r["k"]].append(r["runtime_s"])
            if not byk:
                continue
            ks = sorted(byk)
            q = np.array([np.percentile(byk[k], [25, 50, 75]) for k in ks])
            ax.fill_between(ks, q[:, 0], q[:, 2], color=ps.COLORS[alg], alpha=0.18, linewidth=0)
            ax.plot(ks, q[:, 1], color=ps.COLORS[alg], marker=ps.MARKERS[alg], label=ps.LABELS[alg])
            ps.end_label(ax, ks[-1], q[-1, 1], alg)
        ax.set_yscale("log")
        ax.set_title(m)
        ax.set_xlabel("agents (k)")
    axes[0][0].set_ylabel("runtime, solved runs (s)")
    axes[0][-1].legend(loc="lower right")
    fig.suptitle("Runtime: median with interquartile range", x=0.01, ha="left", fontweight="bold")
    fig.tight_layout()
    fig.savefig(out, dpi=150)
    plt.close(fig)


def summary_md(rows, table, header, path_csv):
    maps = maps_in(rows)
    pairs = paired(rows)
    L = ["# Benchmark summary (Step 8)", "",
         f"Generated by `experiments/analyze.py` from `{os.path.relpath(path_csv, ROOT)}`. Do not edit by hand.", ""]
    L += ["## Setup", "",
          f"- Conflict model: {header.get('conflict_model', '?')}",
          f"- Time limit per instance: {header.get('time_limit_s', '?')} s; workers: {header.get('workers', '?')}",
          f"- Stop rule: {header.get('stop_rule', '?')}",
          f"- Machine: {header.get('processor', '?')}, {header.get('platform', '?')}, Python {header.get('python', '?')}",
          f"- Runs: {len(rows)}; total wall time: {header.get('total_wall_s', '?')} s; git commit {header.get('git_commit', '?')}",
          f"- Invalid solutions rejected by the validator: {sum(r['status'] == 'invalid' for r in rows)}", ""]

    L += ["## Largest k solved in at least 50% of scenarios", "", "| map | CBS | PP |", "|---|---:|---:|"]
    for m in maps:
        L.append(f"| {m} | {max_k_at(table, m, 'cbs')} | {max_k_at(table, m, 'pp')} |")
    L.append("")

    L += ["## Overall success rate (all k each algorithm was run at)", "",
          "| map | CBS solved / runs | PP solved / runs | CBS rate on k both ran | PP rate on k both ran |",
          "|---|---:|---:|---:|---:|"]
    for m in maps:
        c, p = table[(m, "cbs")], table[(m, "pp")]
        both = sorted(set(c) & set(p))
        cs, cn = sum(c[k][0] for k in c), sum(c[k][1] for k in c)
        pps, pn = sum(p[k][0] for k in p), sum(p[k][1] for k in p)
        cb = sum(c[k][0] for k in both) / max(1, sum(c[k][1] for k in both))
        pb = sum(p[k][0] for k in both) / max(1, sum(p[k][1] for k in both))
        L.append(f"| {m} | {cs} / {cn} | {pps} / {pn} | {cb:.1%} | {pb:.1%} |")
    L.append("")

    L += ["## PP suboptimality on instances both algorithms solve", "",
          "Ratio = PP SOC / CBS SOC (CBS is SOC-optimal, so the ratio is >= 1).", "",
          "| map | paired instances | mean ratio | max ratio | share with ratio > 1 |", "|---|---:|---:|---:|---:|"]
    allr = []
    for m in maps:
        rs = [v["pp"]["soc"] / v["cbs"]["soc"] for key, v in pairs.items() if key[0] == m and v["cbs"]["soc"]]
        allr += rs
        if rs:
            L.append(f"| {m} | {len(rs)} | {mean(rs):.4f} | {max(rs):.4f} | {sum(r > 1 for r in rs) / len(rs):.1%} |")
    if allr:
        L.append(f"| **all** | {len(allr)} | {mean(allr):.4f} | {max(allr):.4f} | {sum(r > 1 for r in allr) / len(allr):.1%} |")
    neg = sum(1 for v in pairs.values() if v["pp"]["soc"] < v["cbs"]["soc"])
    L += ["", f"Sanity check: paired instances where PP beat CBS on SOC (would indicate a CBS bug): {neg}.", ""]

    L += ["## Why PP failed", "", "| map | start_blocked | no_path | timeout |", "|---|---:|---:|---:|"]
    for m in maps:
        f = [r for r in rows if r["map"] == m and r["algorithm"] == "pp" and not r["success"]]
        L.append(f"| {m} | {sum(r['fail_reason'] == 'start_blocked' for r in f)} | "
                 f"{sum(r['fail_reason'] == 'no_path' for r in f)} | {sum(r['status'] == 'timeout' for r in f)} |")
    L += ["", "`start_blocked`: a higher-priority agent enters this agent's start cell at t <= 1, which no "
          "plan can avoid under the no-following model (plain PP does not protect lower-priority start cells).", ""]

    L += ["## Success rate by k", ""]
    for m in maps:
        c, p = table[(m, "cbs")], table[(m, "pp")]
        ks = sorted(set(c) | set(p))
        L += [f"### {m}", "", "| k | CBS | PP | CBS median runtime (s) | PP median runtime (s) |", "|---:|---:|---:|---:|---:|"]
        for k in ks:
            def fmt(d):
                return f"{d[k][0]}/{d[k][1]}" if k in d else "-"

            def med(alg):
                v = [r["runtime_s"] for r in rows if r["map"] == m and r["k"] == k and r["algorithm"] == alg and r["success"]]
                return f"{np.median(v):.3f}" if v else "-"
            L.append(f"| {k} | {fmt(c)} | {fmt(p)} | {med('cbs')} | {med('pp')} |")
        L.append("")
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--csv", default=os.path.join(ROOT, "results", "benchmark.csv"))
    ap.add_argument("--out-dir", default=os.path.join(ROOT, "results"))
    args = ap.parse_args()
    ps.setup()
    rows = load(args.csv)
    header = read_header(args.csv)
    table = success_table(rows)
    os.makedirs(os.path.join(args.out_dir, "plots"), exist_ok=True)
    plot_success(rows, table, os.path.join(args.out_dir, "plots", "success_rate.png"))
    plot_runtime(rows, os.path.join(args.out_dir, "plots", "runtime.png"))
    md = summary_md(rows, table, header, args.csv)
    with open(os.path.join(args.out_dir, "summary.md"), "w", encoding="utf-8") as f:
        f.write(md + "\n")
    print(f"wrote {args.out_dir}/summary.md and plots/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
